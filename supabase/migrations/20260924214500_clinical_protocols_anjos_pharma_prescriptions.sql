create or replace function private.finalize_consultation_prescription(
  p_consultation_id bigint,
  p_finalized_at timestamptz
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_prescription public.consultation_prescriptions;
  v_consultation public.clinical_consultations;
  v_patient public.patients;
  v_professional public.profiles;
  v_position public.staff_positions;
  v_identity public.professional_identities;
  v_snapshot jsonb;
  v_suggestions text[];
  v_reviewed text[];
begin
  select * into v_consultation from public.clinical_consultations where id = p_consultation_id for update;
  select coalesce(array_agg(distinct suggestion->>'medication_id'), '{}'::text[]) into v_suggestions
  from jsonb_array_elements(coalesce(v_consultation.selected_diagnosis->'medication_suggestions', '[]'::jsonb)) suggestion;
  select coalesce(array_agg(distinct decision.medication_id), '{}'::text[]) into v_reviewed
  from public.consultation_medication_decisions decision
  where decision.consultation_id = p_consultation_id;
  if not (v_suggestions <@ v_reviewed) then raise exception 'Revise cada sugestão de medicamento antes de concluir.'; end if;
  select * into v_prescription from public.consultation_prescriptions where consultation_id = p_consultation_id for update;
  if v_prescription.id is null then return null; end if;
  if v_prescription.status = 'finalized' then return v_prescription.final_snapshot; end if;
  if not exists (select 1 from public.consultation_prescription_items where prescription_id = v_prescription.id) then return null; end if;
  select * into v_patient from public.patients where id = v_consultation.patient_id;
  select * into v_professional from public.profiles where user_id = v_consultation.professional_id;
  select * into v_position from public.staff_positions where id = v_professional.position_id;
  select * into v_identity from public.professional_identities where user_id = v_professional.user_id and status = 'active';
  if v_identity.user_id is null or v_identity.crm_code !~ '^[0-9]{8}$' or v_identity.signature_image_path is null then
    raise exception 'A identidade profissional ainda está sendo preparada. Gere a assinatura e o CRM antes de concluir.';
  end if;
  update public.consultation_prescription_items set
    professional_name_snapshot = v_professional.display_name,
    crm_snapshot = v_identity.crm_code,
    role_snapshot = v_position.name,
    updated_at = now()
  where prescription_id = v_prescription.id;
  select jsonb_build_object(
    'schema', 'hpsm.rp_prescription.v1',
    'prescription_id', v_prescription.id,
    'consultation_id', p_consultation_id,
    'patient', jsonb_build_object('name', v_patient.name, 'passport', v_patient.passport),
    'professional', jsonb_build_object(
      'id', v_professional.user_id,
      'name', v_professional.display_name,
      'crm_code', v_identity.crm_code,
      'role', v_position.name,
      'signature_image_path', v_identity.signature_image_path
    ),
    'created_at', v_prescription.created_at,
    'finalized_at', p_finalized_at,
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', item.id,
        'medication_id', item.medication_id,
        'rp_name_snapshot', item.rp_name_snapshot,
        'reference_name_snapshot', item.reference_name_snapshot,
        'dose_snapshot', item.dose_snapshot,
        'frequency_snapshot', item.frequency_snapshot,
        'duration_snapshot', item.duration_snapshot,
        'route_snapshot', item.route_snapshot,
        'reason_snapshot', item.reason_snapshot,
        'instructions_snapshot', item.instructions_snapshot,
        'justification_snapshot', item.justification_snapshot,
        'calculated_quantity_snapshot', item.calculated_quantity_snapshot,
        'final_quantity_snapshot', item.final_quantity_snapshot,
        'quantity_override_snapshot', item.quantity_override_snapshot,
        'override_reason', item.override_reason,
        'professional_id', item.professional_id,
        'professional_name_snapshot', item.professional_name_snapshot,
        'crm_snapshot', item.crm_snapshot,
        'role_snapshot', item.role_snapshot,
        'created_at', item.created_at
      ) order by item.created_at, item.id)
      from public.consultation_prescription_items item
      where item.prescription_id = v_prescription.id
    ), '[]'::jsonb),
    'rp_notice', 'As posologias, dosagens e orientações são regras fictícias e simplificadas, destinadas exclusivamente ao uso em RP.'
  ) into v_snapshot;
  update public.consultation_prescriptions set
    status = 'finalized', patient_name_snapshot = v_patient.name,
    patient_passport_snapshot = v_patient.passport,
    professional_name_snapshot = v_professional.display_name,
    crm_snapshot = v_identity.crm_code, role_snapshot = v_position.name,
    final_snapshot = v_snapshot, finalized_at = p_finalized_at, updated_at = now()
  where id = v_prescription.id;
  insert into public.audit_logs (actor_user_id, actor_passport, action, entity_name, entity_id, new_values)
  values (v_professional.user_id, v_professional.passport, 'PRESCRIPTION_FINALIZED', 'consultation_prescriptions', v_prescription.id::text,
    jsonb_build_object('consultation_id', p_consultation_id, 'item_count', jsonb_array_length(v_snapshot->'items')));
  return v_snapshot;
end;
$$;


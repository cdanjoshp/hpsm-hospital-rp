create or replace function private.rp_frequency_doses_per_day(p_frequency text)
returns integer
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_frequency text := lower(regexp_replace(btrim(coalesce(p_frequency, '')), '\s+', ' ', 'g'));
  v_interval integer;
  v_times integer;
begin
  if v_frequency = '' then raise exception 'Informe a frequência.'; end if;
  v_times := nullif((regexp_match(v_frequency, '(^|[^0-9])([1-9]|1[0-9]|2[0-4])\s*x\s*/?\s*dia'))[2], '')::integer;
  if v_times is not null then return v_times; end if;
  v_interval := nullif((regexp_match(v_frequency, '(^|[^0-9])(24|12|8|6|4)\s*/\s*\2\s*h'))[2], '')::integer;
  if v_interval is null then
    v_interval := nullif((regexp_match(v_frequency, 'a cada\s+(24|12|8|6|4)\s+hora'))[1], '')::integer;
  end if;
  if v_interval is null then raise exception 'Use uma frequência RP suportada: 1x/dia a 4x/dia ou intervalos de 24, 12, 8, 6 ou 4 horas.'; end if;
  return 24 / v_interval;
end;
$$;

create or replace function private.rp_quantity(p_frequency text, p_duration_days integer)
returns integer
language plpgsql
immutable
set search_path = ''
as $$
declare
  v_quantity integer;
begin
  if p_duration_days not between 1 and 365 then raise exception 'A duração deve ficar entre 1 e 365 dias.'; end if;
  v_quantity := private.rp_frequency_doses_per_day(p_frequency) * p_duration_days;
  if v_quantity not between 1 and 1000 then raise exception 'A quantidade calculada está fora do limite RP.'; end if;
  return v_quantity;
end;
$$;

create or replace function private.rp_case_signature(p_consultation_id bigint)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(
    (
      select generation.response_payload->'case_signature'
      from public.consultation_ai_generations generation
      where generation.consultation_id = p_consultation_id
        and generation.action_type = 'CLINICAL_SYNTHESIS'
        and generation.status = 'completed'
    ),
    (
      select generation.response_payload->'case_signature'
      from public.consultation_ai_generations generation
      where generation.consultation_id = p_consultation_id
        and generation.action_type = 'EXAM_SUGGESTIONS'
        and generation.status = 'completed'
    ),
    jsonb_build_object('body_system', 'geral', 'case_tags', '[]'::jsonb, 'vital_flags', '[]'::jsonb)
  );
$$;

create or replace function private.rp_medication_context_compatible(
  p_consultation_id bigint,
  p_medication_id text
)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_medication public.rp_medications;
  v_consultation public.clinical_consultations;
  v_allergies text;
  v_signature jsonb;
  v_body_system text;
  v_tags text[];
begin
  select * into v_medication from public.rp_medications where id = p_medication_id and active;
  if v_medication.id is null then return false; end if;
  select * into v_consultation
  from public.clinical_consultations consultation
  where consultation.id = p_consultation_id;
  if v_consultation.id is null then return false; end if;
  select lower(coalesce(patient.allergies, '')) into v_allergies
  from public.patients patient where patient.id = v_consultation.patient_id;
  if exists (
    select 1 from unnest(v_medication.allergy_keywords) keyword
    where char_length(keyword) >= 3 and v_allergies like '%' || lower(keyword) || '%'
  ) then return false; end if;
  v_signature := private.rp_case_signature(p_consultation_id);
  v_body_system := lower(coalesce(v_signature->>'body_system', 'geral'));
  select coalesce(array_agg(lower(value)), '{}'::text[]) into v_tags
  from jsonb_array_elements_text(coalesce(v_signature->'case_tags', '[]'::jsonb)) value;
  if cardinality(v_medication.disallowed_case_tags) > 0
     and v_tags && v_medication.disallowed_case_tags then return false; end if;
  if v_medication.id = 'DORMAX'
     and coalesce(v_consultation.pain_score, 0) < 7
     and not (v_tags && v_medication.allowed_case_tags) then return false; end if;
  if cardinality(v_medication.allowed_body_systems) = 0
     and cardinality(v_medication.allowed_case_tags) = 0 then return true; end if;
  return v_body_system = any(v_medication.allowed_body_systems)
    or v_tags && v_medication.allowed_case_tags;
end;
$$;

create or replace function private.ensure_consultation_prescription(
  p_consultation_id bigint,
  p_actor uuid
)
returns public.consultation_prescriptions
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_prescription public.consultation_prescriptions;
  v_consultation public.clinical_consultations;
  v_passport text;
begin
  select * into v_consultation from public.clinical_consultations where id = p_consultation_id for update;
  if v_consultation.id is null then raise exception 'Consulta não localizada.'; end if;
  if v_consultation.status <> 'in_progress' then raise exception 'A prescrição concluída é imutável.'; end if;
  if not private.can_edit_consultation(p_actor, v_consultation.professional_id) then raise exception 'Acesso não autorizado.' using errcode = '42501'; end if;
  select * into v_prescription from public.consultation_prescriptions where consultation_id = p_consultation_id for update;
  if v_prescription.id is null then
    insert into public.consultation_prescriptions (consultation_id, professional_id)
    values (p_consultation_id, v_consultation.professional_id)
    returning * into v_prescription;
    select passport into v_passport from public.profiles where user_id = p_actor;
    insert into public.audit_logs (actor_user_id, actor_passport, action, entity_name, entity_id, new_values)
    values (p_actor, v_passport, 'PRESCRIPTION_CREATED', 'consultation_prescriptions', v_prescription.id::text,
      jsonb_build_object('consultation_id', p_consultation_id));
  end if;
  return v_prescription;
end;
$$;

create or replace function public.upsert_consultation_prescription_item(
  p_consultation_id bigint,
  p_item_id uuid,
  p_medication_id text,
  p_source text,
  p_reason text,
  p_dose text,
  p_frequency text,
  p_duration_days integer,
  p_route text,
  p_instructions text,
  p_justification text default null,
  p_final_quantity integer default null,
  p_override_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.hpsm_current_actor();
  v_passport text;
  v_prescription public.consultation_prescriptions;
  v_medication public.rp_medications;
  v_item public.consultation_prescription_items;
  v_old public.consultation_prescription_items;
  v_calculated integer;
  v_final integer;
  v_override boolean;
  v_is_suggestion boolean;
begin
  if p_source not in ('ai', 'manual') then raise exception 'Origem da medicação inválida.'; end if;
  select * into v_medication from public.rp_medications where id = upper(btrim(coalesce(p_medication_id, ''))) and active;
  if v_medication.id is null then raise exception 'Medicamento inexistente ou inativo.'; end if;
  if not private.rp_medication_context_compatible(p_consultation_id, v_medication.id) then
    raise exception 'O medicamento é incompatível com o contexto clínico ou com as alergias informadas.';
  end if;
  v_is_suggestion := exists (
    select 1
    from public.clinical_consultations consultation,
      jsonb_array_elements(coalesce(consultation.selected_diagnosis->'medication_suggestions', '[]'::jsonb)) suggestion
    where consultation.id = p_consultation_id and suggestion->>'medication_id' = v_medication.id
  );
  if p_source = 'ai' and not v_is_suggestion then raise exception 'A sugestão de medicamento não pertence ao diagnóstico selecionado.'; end if;
  if char_length(btrim(coalesce(p_reason, ''))) not between 3 and 1000 then raise exception 'Informe o motivo da prescrição.'; end if;
  if char_length(btrim(coalesce(p_dose, ''))) not between 1 and 80
     or char_length(btrim(coalesce(p_frequency, ''))) not between 1 and 120
     or char_length(btrim(coalesce(p_route, ''))) not between 1 and 120
     or char_length(btrim(coalesce(p_instructions, ''))) not between 1 and 500 then
    raise exception 'Revise dose, frequência, via e orientações.';
  end if;
  if v_medication.requires_justification and char_length(btrim(coalesce(p_justification, ''))) not between 3 and 1000 then
    raise exception 'Este medicamento exige justificativa clínica.';
  end if;
  v_calculated := private.rp_quantity(p_frequency, p_duration_days);
  v_final := coalesce(p_final_quantity, v_calculated);
  if v_final not between 1 and 1000 then raise exception 'A quantidade final está fora do limite RP.'; end if;
  v_override := v_final <> v_calculated;
  if v_override and char_length(btrim(coalesce(p_override_reason, ''))) not between 3 and 500 then
    raise exception 'Informe o motivo do ajuste manual da quantidade.';
  end if;
  v_prescription := private.ensure_consultation_prescription(p_consultation_id, v_actor);
  if p_item_id is not null then
    select * into v_old from public.consultation_prescription_items
    where id = p_item_id and prescription_id = v_prescription.id for update;
    if v_old.id is null then raise exception 'Item da prescrição não localizado.'; end if;
    if v_old.medication_id <> v_medication.id then raise exception 'O medicamento de um item existente não pode ser trocado.'; end if;
    update public.consultation_prescription_items set
      source = p_source,
      dose_snapshot = btrim(p_dose),
      frequency_snapshot = btrim(p_frequency),
      duration_snapshot = p_duration_days::text || case when p_duration_days = 1 then ' dia' else ' dias' end,
      duration_days = p_duration_days,
      route_snapshot = btrim(p_route),
      reason_snapshot = btrim(p_reason),
      instructions_snapshot = btrim(p_instructions),
      justification_snapshot = nullif(btrim(coalesce(p_justification, '')), ''),
      calculated_quantity_snapshot = v_calculated,
      final_quantity_snapshot = v_final,
      quantity_override_snapshot = v_override,
      override_reason = case when v_override then btrim(p_override_reason) else null end,
      updated_at = now()
    where id = v_old.id returning * into v_item;
  else
    insert into public.consultation_prescription_items (
      prescription_id, consultation_id, medication_id, source, catalog_version,
      rp_name_snapshot, reference_name_snapshot, dose_snapshot, frequency_snapshot,
      duration_snapshot, duration_days, route_snapshot, reason_snapshot,
      instructions_snapshot, justification_snapshot, calculated_quantity_snapshot,
      final_quantity_snapshot, quantity_override_snapshot, override_reason, professional_id
    ) values (
      v_prescription.id, p_consultation_id, v_medication.id, p_source, v_medication.version,
      v_medication.rp_name, v_medication.reference_name, btrim(p_dose), btrim(p_frequency),
      p_duration_days::text || case when p_duration_days = 1 then ' dia' else ' dias' end,
      p_duration_days, btrim(p_route), btrim(p_reason), btrim(p_instructions),
      nullif(btrim(coalesce(p_justification, '')), ''), v_calculated, v_final,
      v_override, case when v_override then btrim(p_override_reason) else null end,
      v_prescription.professional_id
    ) returning * into v_item;
  end if;
  insert into public.consultation_medication_decisions (
    consultation_id, medication_id, source, decision, reason, actor_user_id
  ) values (p_consultation_id, v_medication.id, p_source, 'accepted', btrim(p_reason), v_actor);
  select passport into v_passport from public.profiles where user_id = v_actor;
  insert into public.audit_logs (actor_user_id, actor_passport, action, entity_name, entity_id, old_values, new_values)
  values (
    v_actor, v_passport,
    case when p_item_id is null and p_source = 'manual' then 'MEDICATION_ADDED_MANUALLY'
         when p_item_id is null then 'MEDICATION_SUGGESTION_ACCEPTED'
         else 'PRESCRIPTION_ITEM_UPDATED' end,
    'consultation_prescription_items', v_item.id::text,
    case when v_old.id is null then null else to_jsonb(v_old) - 'professional_id' end,
    (to_jsonb(v_item) - 'professional_id') || jsonb_build_object('calculated_quantity', v_calculated, 'final_quantity', v_final)
  );
  if v_override then
    insert into public.audit_logs (actor_user_id, actor_passport, action, entity_name, entity_id, new_values)
    values (v_actor, v_passport, 'PRESCRIPTION_QUANTITY_OVERRIDDEN', 'consultation_prescription_items', v_item.id::text,
      jsonb_build_object('calculated_quantity', v_calculated, 'final_quantity', v_final, 'reason', btrim(p_override_reason)));
  end if;
  return to_jsonb(v_item) - 'professional_id';
exception when unique_violation then
  raise exception 'Este medicamento já integra a prescrição. Edite o item existente.';
end;
$$;

create or replace function public.reject_consultation_medication_suggestion(
  p_consultation_id bigint,
  p_medication_id text,
  p_reason text default null
)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := private.hpsm_current_actor();
  v_prescription public.consultation_prescriptions;
  v_medication_id text := upper(btrim(coalesce(p_medication_id, '')));
  v_passport text;
begin
  if not exists (
    select 1
    from public.clinical_consultations consultation,
      jsonb_array_elements(coalesce(consultation.selected_diagnosis->'medication_suggestions', '[]'::jsonb)) suggestion
    where consultation.id = p_consultation_id and suggestion->>'medication_id' = v_medication_id
  ) then raise exception 'Sugestão de medicamento não localizada.'; end if;
  v_prescription := private.ensure_consultation_prescription(p_consultation_id, v_actor);

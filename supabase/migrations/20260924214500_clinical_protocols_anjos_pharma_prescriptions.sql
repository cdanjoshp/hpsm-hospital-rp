  insert into public.consultation_medication_decisions (consultation_id, medication_id, source, decision, reason, actor_user_id)
  values (p_consultation_id, v_medication_id, 'ai', 'rejected', nullif(btrim(coalesce(p_reason, '')), ''), v_actor);
  select passport into v_passport from public.profiles where user_id = v_actor;
  insert into public.audit_logs (actor_user_id, actor_passport, action, entity_name, entity_id, new_values)
  values (v_actor, v_passport, 'MEDICATION_SUGGESTION_REJECTED', 'clinical_consultations', p_consultation_id::text,
    jsonb_build_object('medication_id', v_medication_id, 'reason', nullif(btrim(coalesce(p_reason, '')), '')));
end;
$$;


  moderation_reason text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint clinical_protocols_state_check check (state in ('CANDIDATE', 'LEARNED', 'CONSOLIDATED')),
  constraint clinical_protocols_moderation_check check (moderation_status in ('active', 'inactive', 'quarantined')),
  constraint clinical_protocols_version_check check (version >= 0),
  constraint clinical_protocols_observed_check check (observed_count >= 0),
  constraint clinical_protocols_body_system_check check (body_system ~ '^[a-z0-9_]{2,60}$'),
  constraint clinical_protocols_display_name_check check (char_length(btrim(display_name)) between 3 and 160)
);


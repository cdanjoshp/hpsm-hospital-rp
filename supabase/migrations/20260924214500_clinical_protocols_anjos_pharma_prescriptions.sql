-- HPSM Rollup 4: protocolos autoalimentados, catálogo Anjos Pharma e prescrições RP.
-- Não cria estoque, saldo, movimentação, entrada ou saída de medicamentos.

create table public.rp_medications (
  id text primary key,
  rp_name text not null unique,
  reference_name text not null,
  category text not null,
  active boolean not null default true,
  controlled boolean not null default false,
  antibiotic boolean not null default false,
  requires_justification boolean not null default false,
  allowed_body_systems text[] not null default '{}'::text[],
  allowed_case_tags text[] not null default '{}'::text[],
  disallowed_case_tags text[] not null default '{}'::text[],
  allergy_keywords text[] not null default '{}'::text[],
  default_dose text not null,
  default_frequency text not null,
  default_duration text not null,
  default_duration_days smallint not null,
  default_route text not null,
  default_instructions text not null,
  default_doses_per_day smallint not null,
  default_as_needed boolean not null default false,
  version integer not null default 1,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint rp_medications_id_check check (id ~ '^[A-Z0-9_]{3,40}$'),
  constraint rp_medications_text_check check (
    char_length(btrim(rp_name)) between 2 and 100
    and char_length(btrim(reference_name)) between 2 and 160
    and char_length(btrim(default_dose)) between 1 and 80
    and char_length(btrim(default_frequency)) between 1 and 120
    and char_length(btrim(default_duration)) between 1 and 80
    and char_length(btrim(default_route)) between 1 and 120
    and char_length(btrim(default_instructions)) between 1 and 500
  ),
  constraint rp_medications_duration_check check (default_duration_days between 1 and 365),
  constraint rp_medications_frequency_check check (default_doses_per_day between 1 and 24),
  constraint rp_medications_version_check check (version >= 1),
  constraint rp_medications_justification_check check (
    not (controlled or antibiotic) or requires_justification
  )
);

create table public.rp_medication_versions (
  id bigint generated by default as identity primary key,
  medication_id text not null references public.rp_medications(id) on delete cascade,
  version integer not null,
  snapshot jsonb not null,
  changed_by uuid references public.profiles(user_id) on delete set null,
  change_reason text,
  created_at timestamptz not null default now(),
  constraint rp_medication_versions_unique unique (medication_id, version),
  constraint rp_medication_versions_snapshot_check check (jsonb_typeof(snapshot) = 'object')
);

create table public.clinical_protocol_settings (
  singleton boolean primary key default true,
  candidate_to_learned_count integer not null,
  learned_to_consolidated_count integer not null,
  merge_similarity_threshold numeric(4,3) not null,
  related_similarity_threshold numeric(4,3) not null,
  max_related_protocols integer not null,
  updated_at timestamptz not null default now(),
  constraint clinical_protocol_settings_singleton_check check (singleton),
  constraint clinical_protocol_settings_counts_check check (
    candidate_to_learned_count >= 2
    and learned_to_consolidated_count > candidate_to_learned_count
    and max_related_protocols between 1 and 5
  ),
  constraint clinical_protocol_settings_thresholds_check check (
    merge_similarity_threshold between 0 and 1
    and related_similarity_threshold between 0 and 1
  )
);

create table public.clinical_protocols (
  id uuid primary key default gen_random_uuid(),
  fingerprint text not null unique,
  display_name text not null,

create table public.patient_health_plan_requests (
  id bigint generated by default as identity primary key,
  patient_id bigint not null references public.patients(id) on update restrict on delete restrict,
  attendance_id bigint not null unique references public.attendances(id) on update restrict on delete restrict,
  status text not null default 'pending'
    constraint patient_health_plan_requests_status_check
    check (status in ('pending', 'approved', 'rejected')),
  requested_at timestamptz not null default now(),
  reviewed_by uuid references public.profiles(user_id) on update restrict on delete set null,
  reviewed_at timestamptz,
  rejection_reason text,
  coverage_start timestamptz,
  coverage_end timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint patient_health_plan_requests_resolution_check check (
    (
      status = 'pending'
      and reviewed_by is null
      and reviewed_at is null
      and rejection_reason is null
      and coverage_start is null
      and coverage_end is null
    )
    or
    (
      status = 'approved'
      and reviewed_by is not null
      and reviewed_at is not null
      and rejection_reason is null
      and coverage_start is not null
      and coverage_end is not null
      and coverage_end > coverage_start
    )
    or
    (
      status = 'rejected'
      and reviewed_by is not null
      and reviewed_at is not null
      and char_length(btrim(rejection_reason)) between 10 and 2000
      and coverage_start is null
      and coverage_end is null
    )
  )
);

create index patient_health_plan_requests_pending_idx
  on public.patient_health_plan_requests (requested_at, id)
  where status = 'pending';

create index patient_health_plan_requests_patient_approved_idx

create or replace function public.get_patient_health_plan_states(p_patient_ids bigint[])
returns table (
  patient_id bigint,
  status text,
  activated_at timestamptz,
  valid_until timestamptz,
  authorized_by uuid,
  authorized_by_name text,
  pending_request_id bigint,
  pending_requested_at timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if (select auth.uid()) is null
     or not private.has_permission((select auth.uid()), 'patients.view') then
    raise exception 'Você não possui permissão para consultar pacientes.';
  end if;

  if p_patient_ids is null or cardinality(p_patient_ids) = 0 then
    return;
  end if;

  return query
  select
    patient.id,
    case
      when approved.id is not null and approved.coverage_end > now() then 'active'
      when approved.id is not null then 'expired'
      when pending.id is not null then 'awaiting_confirmation'
      else 'none'
    end,
    approved.coverage_start,
    approved.coverage_end,
    approved.reviewed_by,
    reviewer.display_name,
    pending.id,
    pending.requested_at
  from public.patients as patient
  left join lateral (
    select request.id, request.coverage_start, request.coverage_end, request.reviewed_by
    from public.patient_health_plan_requests as request
    where request.patient_id = patient.id
      and request.status = 'approved'
    order by request.coverage_end desc, request.id desc
    limit 1
  ) as approved on true
  left join public.profiles as reviewer on reviewer.user_id = approved.reviewed_by
  left join lateral (
    select request.id, request.requested_at
    from public.patient_health_plan_requests as request
    where request.patient_id = patient.id
      and request.status = 'pending'
    order by request.requested_at asc, request.id asc
    limit 1
  ) as pending on true
  where patient.id = any(p_patient_ids);
end;
$$;

revoke all on function public.get_patient_health_plan_states(bigint[]) from public, anon, authenticated, service_role;
grant execute on function public.get_patient_health_plan_states(bigint[]) to authenticated;
grant execute on function public.get_patient_health_plan_states(bigint[]) to service_role;

create or replace function public.review_patient_health_plan_request(
  p_request_id bigint,
  p_decision text,
  p_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor_id uuid := (select auth.uid());
  v_current_end timestamptz;
  v_decided_at timestamptz := now();
  v_request public.patient_health_plan_requests%rowtype;
  v_start timestamptz;
begin
  if v_actor_id is null or not private.has_permission(v_actor_id, 'healthplans.review') then
    raise exception 'Você não possui permissão para analisar planos de saúde.';
  end if;

  if p_decision not in ('approved', 'rejected') then
    raise exception 'Decisão inválida.';
  end if;

  select request.*
  into v_request
  from public.patient_health_plan_requests as request
  where request.id = p_request_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Solicitação não localizada.';
  end if;

  if v_request.status <> 'pending' then
    if v_request.status = p_decision then
      return jsonb_build_object(
        'id', v_request.id,
        'status', v_request.status,
        'valid_until', v_request.coverage_end,
        'already_reviewed', true
      );
    end if;
    raise exception using errcode = 'P0001', message = 'A solicitação já possui uma decisão diferente.';
  end if;

  perform 1
  from public.patients as patient
  where patient.id = v_request.patient_id
  for update;

  if not found then
    raise exception using errcode = 'P0002', message = 'Paciente não localizado.';
  end if;

  if p_decision = 'approved' then
    select max(request.coverage_end)
    into v_current_end
    from public.patient_health_plan_requests as request
    where request.patient_id = v_request.patient_id
      and request.status = 'approved';

    v_start := greatest(v_decided_at, coalesce(v_current_end, v_decided_at));

    update public.patient_health_plan_requests
    set status = 'approved',
        reviewed_by = v_actor_id,
        reviewed_at = v_decided_at,
        rejection_reason = null,
        coverage_start = v_start,
        coverage_end = v_start + interval '30 days'
    where id = v_request.id
    returning * into v_request;
  else
    if char_length(btrim(coalesce(p_reason, ''))) < 10 then
      raise exception 'Informe o motivo da recusa com pelo menos 10 caracteres.';
    end if;
    if char_length(btrim(p_reason)) > 2000 then
      raise exception 'O motivo da recusa deve ter no máximo 2000 caracteres.';
    end if;

    update public.patient_health_plan_requests
    set status = 'rejected',
        reviewed_by = v_actor_id,
        reviewed_at = v_decided_at,
        rejection_reason = btrim(p_reason),
        coverage_start = null,
        coverage_end = null
    where id = v_request.id
    returning * into v_request;
  end if;

  return jsonb_build_object(
    'id', v_request.id,
    'status', v_request.status,
    'valid_until', v_request.coverage_end,
    'already_reviewed', false
  );
end;
$$;

revoke all on function public.review_patient_health_plan_request(bigint, text, text) from public, anon, authenticated, service_role;
grant execute on function public.review_patient_health_plan_request(bigint, text, text) to authenticated;
grant execute on function public.review_patient_health_plan_request(bigint, text, text) to service_role;

